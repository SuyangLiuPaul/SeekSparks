#!/usr/bin/env python3
"""Repair the English KJV defects found by check 27 (docs/DATA-INTEGRITY.md).

Check 26 held the Chinese text against outside witnesses. This does the same
for the English, and finds the same shape of defect: text that renders
perfectly, reads plausibly, and is wrong.

THE WITNESSES. Three independent electronic King James texts, fetched fresh
and compared with each other before being compared with us:

  * getbible.net v2 (api.getbible.net/v2/kjv) — the CrossWire/Blayney 1769 line
  * openbible.com's Pure Cambridge Edition (bibleprotector.com line), which
    brackets the words the translators supplied
  * scrollmapper's public-domain bible_databases export

They agree with each other in 30,058 of 31,102 verses. Where they disagree
they are not used: every repair below is gated on all three reading the same
thing, so no single upstream's editorial habits can propagate into our asset.

THE RULE, stated so a later reader can disagree with it: **a systematic
difference is an edition, a one-off difference is an error.** `assets/kjv.json`
departs from all three witnesses in 851 verses, but 748 of those departures are
this text's own orthography, applied across the corpus — shew/show,
neighbour/neighbor, honour/honor, carcase/carcass, jubile/jubilee,
ringstraked/ring-streaked, intreat/entreat, firstborn/first born, and some
forty proper-name spellings (Malchi-shua/Melchishua, Adoni-zedek/Adonizedec).
Those are left exactly as they are. This file is an Americanised, modernised
revision of the KJV, and revising it back would be inventing a fourth edition.

What is repaired is the residue: 101 sites where the difference is not a
spelling of the same word but a *different* word, a different number, or a word
that is simply gone — and where all three witnesses agree on the reading. Some
are visibly broken ("Three items in the year", "c|alleth", "the son Uri", "So
they look up Jonah"); most are not. "Cushy" for the messenger Cushi is legible
eight times over. "the land of their enemies" for "the hand of their enemies"
reads without a stumble. That is the point: nothing here would ever have been
caught by reading the app.

Three further defect classes, all typographic and all silent:

  * 31,101 of 31,102 verses in `kjv.json` end in a trailing " \\n". Invisible in
    the reader, but it is inside the string the app searches, copies and hands
    to the concordance.
  * 11,409 verses in `kjvs.json` print a space before the punctuation —
    "and was sick : and he sent". This one the reader can see.
  * 10 verses in `kjv.json` carry a stray "|" left by a conversion. Six sit
    harmlessly at a verse end, two at a verse start, and two land inside a
    word: "he that c|alleth for the waters", "hide nothing from m|e".

And one truncation: Esther 8:9, the longest verse in the Bible at 528
characters, stops at 499 in `kjv.json`, mid-clause, dropping "according to
their language". It is the only verse in the file over 443 characters, so a
500-character cap upstream could only ever have shown itself here — and did.
`kjvs.json` carries the verse whole, which is how the loss is provable.

Run with no flags to verify — exit 0 means nothing left to repair.
Run with --write to apply. Idempotent either way.
"""

