# The one truncation. It restores by appending, so unlike every other site the
# repaired text still contains the broken text, and "already done" has to be
# asked as a suffix question rather than a substring one.
TRUNCATED = (
    ("Esther", 8, 9),
    "and to the Jews according to their writing, and",
    "and to the Jews according to their writing, and according to their language.",
)


def keep_mask(text: str) -> list[bool]:
    """Which characters survive the typographic repair.

    Expressed as a mask rather than a rewrite because the same repair has to
    be applied to `assets/tagged/kjvs/`, where the verse is split across runs
    and a space can sit in one run with the colon it precedes in the next.
    Every repair here is a deletion, so a mask is enough — and it guarantees
    the plain file and the tagged layer cannot drift apart.
    """
    keep = [ch != "|" for ch in text]
    kept = [i for i, k in enumerate(keep) if k]
    piped = "".join(text[i] for i in kept)
    for match in SPACE_BEFORE_PUNCT.finditer(piped):
        for j in range(match.start(), match.end()):
            keep[kept[j]] = False
    for span in (range(len(piped)), reversed(range(len(piped)))):
        for j in span:
            if not piped[j].isspace():
                break
            keep[kept[j]] = False
    return keep


def normalise(text: str) -> str:
    """The typographic repairs: stray pipes, edge whitespace, spaced punctuation."""
    return "".join(c for c, k in zip(text, keep_mask(text)) if k)


def load(path: Path) -> tuple[list[dict], bool]:
    data = json.loads(path.read_text(encoding="utf-8"))
    indented = path.read_text(encoding="utf-8")[:3].startswith("[\n ")
    return data, indented


def save(path: Path, data: list[dict], indented: bool) -> None:
    with path.open("w", encoding="utf-8") as fh:
        if indented:
            json.dump(data, fh, ensure_ascii=False, indent=2)
        else:
            json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))


def main() -> int:
    ap = argparse.ArgumentParser(description="Repair check-27 defects in the English KJV assets.")
    ap.add_argument("--write", action="store_true", help="apply the repairs (default: verify only)")
    args = ap.parse_args()

    sites = {(b, c, v): (old, new) for b, c, v, old, new in WORD_SITES}
    if len(sites) != len(WORD_SITES):
        print("FAIL: duplicate reference in WORD_SITES", file=sys.stderr)
        return 2

    outstanding = 0
    failures: list[str] = []
    changed_files: list[tuple[Path, list[dict], bool]] = []

    for name in ("kjv.json", "kjvs.json"):
        path = ROOT / "assets" / name
        data, indented = load(path)
        typographic = 0
        words = 0
        seen: set[tuple[str, int, int]] = set()

        for row in data:
            ref = (row["book"], int(row["chapter"]), int(row["verse"]))
            text = row["text"]

            clean = normalise(text)
            if clean != text:
                typographic += 1
                text = clean

            if name == "kjv.json" and ref in sites:
                old, new = sites[ref]
                seen.add(ref)
                hits = text.count(old)
                if hits == 1:
                    text = text.replace(old, new)
                    words += 1
                elif hits > 1:
                    failures.append(f"{ref[0]} {ref[1]}:{ref[2]}: {old!r} is not unique")

            if name == "kjv.json" and ref == TRUNCATED[0]:
                broken, whole = TRUNCATED[1], TRUNCATED[2]
                if text.endswith(whole):
                    pass
                elif text.endswith(broken):
                    text = text[: -len(broken)] + whole
                    words += 1
                else:
                    failures.append("Esther 8:9: neither the truncated nor the whole ending")

            if text != row["text"]:
                row["text"] = text

        if name == "kjv.json":
            for ref in sites.keys() - seen:
                failures.append(f"{ref[0]} {ref[1]}:{ref[2]}: reference not present in {name}")

        total = typographic + words
        outstanding += total
        print(f"{name}: {typographic} verses with typographic defects, "
              f"{words} verses with word-level defects")
        if total:
            changed_files.append((path, data, indented))

    # The tagged layer holds the same verse split into runs, and the loader
    # renders runs where the search pane reads plain text. Repairing one and
    # not the other makes the same verse look different in two panes.
    tagged_total = 0
    tagged_books = 0
    for path in sorted((ROOT / "assets" / "tagged" / "kjvs").glob("*.json")):
        book = json.loads(path.read_text(encoding="utf-8"))
        touched = 0
        for runs in book.values():
            joined = "".join(run["w"] for run in runs)
            mask = keep_mask(joined)
            if all(mask):
                continue
            touched += 1
            at = 0
            for run in runs:
                width = len(run["w"])
                run["w"] = "".join(
                    c for c, k in zip(run["w"], mask[at:at + width]) if k)
                at += width
        outstanding += touched
        tagged_total += touched
        if touched:
            tagged_books += 1
            changed_files.append((path, book, False))
    print(f"tagged/kjvs: {tagged_total} verses with typographic defects "
          f"across {tagged_books} of 66 books")

    if failures:
        for line in failures:
            print(f"FAIL: {line}", file=sys.stderr)
        return 2

    if not outstanding:
        print("nothing to repair")
        return 0

    if not args.write:
        print(f"{outstanding} verses would be repaired; re-run with --write")
        return 1

    for path, data, indented in changed_files:
        save(path, data, indented)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
